"""Writes art/generated/MANIFEST.md from a directory walk (so 'every file' stays true).
Run after aether_art.py:  python art/generated/tools/make_manifest.py"""
import re
from pathlib import Path

from PIL import Image

GEN = Path(__file__).resolve().parent.parent
for d in ("svg", "tools", "previews"):
    (GEN / d).mkdir(exist_ok=True)
    (GEN / d / ".gdignore").write_text("", encoding="utf-8")  # Godot skips this folder if copied

TYPE_DOC = {
    "ground": "standard movement tile (3 variants: ground, ground_v2, ground_v3 - pick by hash to break repetition)",
    "ground_v2": "ground variant 2", "ground_v3": "ground variant 3",
    "stone": "raised stone cover, raise 0.35 (not in any map_legend; used on maps)",
    "obstacle": "blocked tile, raise 0.8, tower-themed topper",
    "bridge": "crossable chokepoint, deck runs along the board X axis",
    "bridge_y": "same bridge, deck runs along the board Y axis",
    "capsule_node": "deployment/recharge node floor socket (stand prop capsule_node on it)",
    "player_symbol": "player victory anchor floor seal (stand prop player_sigil on it)",
    "enemy_symbol": "enemy victory anchor floor seal (stand prop enemy_sigil on it)",
    "player_spawn": "player deployment zone (cyan)", "enemy_spawn": "enemy deployment zone (ember)",
    "relic": "optional scoring objective floor seal (stand prop relic on it)",
    "warp_gate": "teleport tile floor ring (stand prop portal on it)",
    "elevation": "high-ground tile, raise 0.6", "hazard": "environmental damage/status tile",
    "forest": "nature terrain", "lava": "fire terrain", "water": "water terrain", "ice": "ice terrain",
    "metal": "technology terrain", "shadow": "dark terrain", "crystal": "crystal terrain", "mixed": "mixed terrain",
}


def purpose(rel):
    p = rel.split("/")
    stem = Path(rel).stem
    if p[1] == "tiles":
        return "%s - %s" % (p[2], TYPE_DOC.get(stem, stem))
    if p[1] == "props":
        return {"player_sigil": "Player Sigil: cyan crystal on pedestal", "enemy_sigil": "Enemy Sigil: ember crystal on spiked pedestal",
                "capsule_node": "Capsule node: hex crystal vessel in a tilted gold gyroscope cage on a plinth",
                "relic": "Golden relic triangle on a stand", "portal": "Violet portal ring (warp gate)"}[stem]
    if p[1] == "icons":
        return "Element family icon: %s" % stem.title()
    if p[1] == "tokens":
        if p[2] == "frames":
            team, fam = stem.split("_", 1)
            return "Unit token frame, %s team, %s family (creature slot r=41 @ (64,60) in SVG units)" % (team, fam.title())
        if p[2] == "silhouettes":
            return "Stand-in creature silhouette: %s (Soft Silver; modulate freely)" % stem
        return "Composited sample token (frame + silhouette) for review"
    if p[1] == "ui":
        return {"buttons": "Command button %s" % stem.replace("btn_", "").replace("_", " / "),
                "turn_order": "Turn-order slot frame %s" % stem.replace("slot_", ""),
                "objective": "Objective checkbox %s" % stem.replace("checkbox_", ""),
                "panel": "Panel %s (gold/navy)" % stem.replace("panel_", "")}[p[2]]
    return ""


def rows(kind):
    out = []
    for f in sorted((GEN / kind).rglob("*.%s" % kind)):
        rel = f.relative_to(GEN).as_posix()
        size = f.stat().st_size
        if kind == "png":
            with Image.open(f) as im:
                dims = "%dx%d" % im.size
        else:
            m = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', f.read_text(encoding="utf-8")[:300])
            dims = "%sx%s vb" % m.groups()
        out.append((rel, dims, size))
    return out


png, svg = rows("png"), rows("svg")
prev = sorted((GEN / "previews").glob("*.png"))
total_png = sum(r[2] for r in png)
total_svg = sum(r[2] for r in svg)

L = []
w = L.append
w("# Aether Sigil - generated placeholder art MANIFEST")
w("")
w("Generated by `tools/aether_art.py` (art) and `tools/make_manifest.py` (this file). Original work; every colour is a")
w("blend of the 7 brand tokens (same maths as `game/scripts/theme_colors.gd`). Re-run both scripts to rebuild.")
w("")
w("- **%d PNG** (%.1f MB) under `png/`, **%d SVG** sources (%.1f MB) under `svg/`, %d review previews under `previews/`." %
  (len(png), total_png / 1e6, len(svg), total_svg / 1e6, len(prev)))
w("- Every PNG has an SVG twin at the same relative path (`png/x/y.png` <-> `svg/x/y.svg`). SVG and PNG are drawn")
w("  from one primitive list, so they match. PNGs are transparent, 4x supersampled, LANCZOS-downscaled.")
w("")
w("## Godot 4.7 import guide")
w("")
w("1. `res://` is the `game/` folder (that is where `project.godot` lives). Copy **`art/generated/png/`** to")
w("   **`game/art/generated/png/`**, so a file is `res://art/generated/png/tiles/T01_verdant_spire/ground.png`.")
w("   Don't copy `svg/`, `tools/` or `previews/`. If you copy the whole folder anyway, each one has a `.gdignore`")
w("   so Godot skips it.")
w("2. Import settings (Import dock, then *Save as Default* for Texture2D):")
w("   - Compress: *Lossless* for UI, or *VRAM Compressed* for tiles and tokens on mobile.")
w("   - Mipmaps: **on** for tiles, props and tokens (they are drawn at 0.33-0.5x). Off for UI.")
w("   - Project Settings > Rendering > Textures > Canvas Textures > Default Texture Filter: **Linear Mipmap**.")
w("     This is not pixel art, so never use Nearest.")
w("   - Fix Alpha Border: on. Premult Alpha: off.")
w("3. You can import the SVGs directly too (Godot rasterises them with ThorVG; set `svg/scale` = 2.0 to match the")
w("   PNGs). The PNGs are the tested path.")
w("")
w("### Isometric tiles: `png/tiles/<Txx_tower>/<type>.png` - 256x320 px (SVG 128x160 at 2x)")
w("")
w("- Top face = 2:1 diamond, **128x64 SVG units** (256x128 px in the PNG).")
w("- **Anchor = centre of the ground-plane diamond = SVG (64,124) = PNG pixel (128,248).** It is the same point on")
w("  every tile, raised or not. Raised tiles lift the top face by `raise x 64` units: stone 0.35, elevation 0.6,")
w("  obstacle 0.8, everything else a 6-unit slab. These are the same `raise` values as `game/data/game_rules.json`.")
w("- Sprite2D recipe for the current board (`board_view.gd`: TILE_W 84, TILE_H 42):")
w("  ```gdscript")
w("  var s := Sprite2D.new()")
w("  s.texture = load(\"res://art/generated/png/tiles/%s/%s.png\" % [tower_folder, type])")
w("  s.centered = false")
w("  s.offset = Vector2(-128, -248)        # texture pixels: anchor -> origin")
w("  s.scale = Vector2.ONE * (84.0 / 256.0)  # = 0.328125; PNG top face is 256 px wide")
w("  s.position = tile_center(c)           # ground-plane centre, NOT top_center()")
w("  ```")
w("  For TILE_W = 128 use scale 0.5. TileMapLayer/TileSet alternative: tile_shape Isometric, tile_size (256,128),")
w("  one 256x320 region per tile, `texture_origin = Vector2i(0, 88)` (ground centre 248 minus region centre 160;")
w("  Godot draws the region centred on the cell, shifted by -texture_origin). UNVERIFIED in-engine: if tiles sit")
w("  88 px off, flip the sign. The Sprite2D recipe above is the one the stage previews were built with.")
w("- Draw order: back-to-front by screen Y of the ground centre (`y_sort_enabled`, or sort by x+y as `board_view.gd`")
w("  already does). Top faces are grown ~0.4 SVG units, so adjacent tiles overlap slightly and show no seams.")
w("- Ground has three variants (`ground`, `ground_v2`, `ground_v3`). Pick one with `(x*7 + y*13) % 3`.")
w("- Bridges: use `bridge` when the neighbouring bridge or walkable tile is along the board X axis, `bridge_y` when")
w("  it is along the Y axis.")
w("- Tiles that host a standing object (player/enemy_symbol, capsule_node, relic, warp_gate) are floor engravings")
w("  only. Stack the matching prop on top as a separate sprite, so you can animate it.")
w("")
w("### Props: `png/props/*.png` - 256x384 px (SVG 128x192 at 2x)")
w("")
w("- **Foot anchor = SVG (64,176) = PNG pixel (128,352).** Put it on the tile's TOP-face centre (`top_center(c)`).")
w("- Sprite2D: `centered=false, offset=(-128,-352)`. Use scale **0.25-0.33** on the 84 px board (the preview uses")
w("  0.275 = 0.55 x 0.5). Give it the same y-sort key as its tile + 0.5 so units can stand in front.")
w("- The capsule node is a faceted hex-crystal vessel in a gold gyroscope cage with two rings tilted +-55 degrees.")
w("  It deliberately has **no** equator band, no front button and no two-tone sphere.")
w("")
w("### Element icons: `png/icons/elements/*.png` - 256x256 (SVG 64x64 at 4x)")
w("")
w("One per `element_family` in the bible (Fire, Water, Wind, Earth, Wood, Ice, Thunder, Light, Dark, Tech, Space,")
w("Arcane). The ring colour is `theme_colors.gd family()`. Use them in a TextureRect with expand mode")
w("*Keep Aspect Centered*; they read cleanly down to 24 px.")
w("")
w("### Unit tokens: `png/tokens/` - 256x256 (SVG 128x128 at 2x)")
w("")
w("- `frames/<ally|enemy>_<family>.png`: the outer ring is the team colour (ally = Aether Cyan, enemy = Ember), the")
w("  inner ring is the element, and the element badge sits at the bottom. **Creature slot: a circle of radius 82 px")
w("  centred at PNG (128,120).**")
w("- `silhouettes/*.png` (256x256): stag, hopper, phoenix, colossus, beetle, drake. These are Soft Silver stand-ins.")
w("  Place each as a child Sprite2D centred on the slot, scaled to 0.72 of the slot box (see `samples/`), and use")
w("  `modulate` to tint.")
w("- Token foot: put the badge bottom (PNG (128,~250)) on `top_center(c)`. Use scale ~0.25 on the 84 px board.")
w("")
w("### UI: `png/ui/`")
w("")
w("- `buttons/btn_<move|attack|skill|defend|wait>_<normal|pressed|disabled>.png`: 192x192. Use a TextureButton")
w("  (normal / pressed / disabled textures). The art has no text: put a Label under the button so it can be localised.")
w("- `turn_order/slot_<ally|enemy>[_active].png`: 144x144. Put the index number as a Label over the top-left corner")
w("  triangle (about 0-40 px) and the portrait inside at inset 16 px.")
w("- `objective/checkbox_<unchecked|checked|failed>.png`: 128x128. Use CheckBox theme icons at 24-32 px.")
w("- `panel/panel_border.png`: 384x384, for a **NinePatchRect / StyleBoxTexture with all patch margins = 56 px**.")
w("  The corner ornaments sit inside the 56 px corners. `panel_header.png` (384x64) is a title plaque; use")
w("  NinePatch margins left/right 40, top/bottom 0.")
w("")
w("### Data notes for the dev")
w("")
w("- The tile set covers all **21 tile types used in any `map_grid`** of the 120 stages. `stone` appears in grids")
w("  but in no `map_legend`.")
w("- `sky`, `ruins`, `space` and `rift` are legend-only: they never appear on a map, so no art was made for them.")
w("  The generator can add them.")
w("- Tower folders: " + ", ".join("`%s`" % d.name for d in sorted((GEN / "png" / "tiles").iterdir())) + ".")
w("")
w("## Review previews (`previews/`, not game assets)")
w("")
w("| file | bytes | what |")
w("|---|---:|---|")
for f in prev:
    what = "stage composite built with only the anchors above" if f.name.startswith("stage_") else "contact sheet"
    w("| `previews/%s` | %d | %s |" % (f.name, f.stat().st_size, what))
w("")
w("## Tools")
w("")
w("| file | what |")
w("|---|---|")
w("| `tools/aether_art.py` | the generator (SVG + Pillow PNG from one primitive list). `--first` = only tower T01, for fast iteration |")
w("| `tools/make_manifest.py` | writes this file |")
w("")
w("## Every file (PNG; the SVG twin is at `svg/<same path>.svg`)")
w("")
w("| path | px | bytes (png) | bytes (svg) | purpose |")
w("|---|---|---:|---:|---|")
svg_sizes = {r[0][4:-4]: (r[1], r[2]) for r in svg}
for rel, dims, size in png:
    key = rel[4:-4]
    sv = svg_sizes.get(key, ("-", 0))
    w("| `%s` | %s | %d | %d | %s |" % (rel, dims, size, sv[1], purpose(rel)))
missing = set(svg_sizes) - {r[0][4:-4] for r in png}
if missing:
    w("")
    w("SVG without PNG: " + ", ".join(sorted(missing)))
(GEN / "MANIFEST.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("png", len(png), "svg", len(svg), "previews", len(prev), "svg-only", len(missing))
